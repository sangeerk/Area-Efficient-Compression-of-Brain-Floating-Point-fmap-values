`timescale 1ns / 1ps

module axi_wrapper_tb;
    // Clock and Reset
    reg aclk;
    reg aresetn;
    
    // AXI Stream Slave (Input to Decompressor)
    reg [15:0] s_axis_tdata;
    reg s_axis_tvalid;
    wire s_axis_tready;
    reg s_axis_tlast;
    
    // AXI Stream Master (Output from Decompressor)
    wire [15:0] m_axis_tdata;
    wire m_axis_tvalid;
    reg m_axis_tready;
    wire m_axis_tlast;

    parameter CLK_PERIOD = 10; 
    
    // File I/O Handlers & Variables
    integer file_in, file_out;
    integer status;
    reg [15:0] temp_val;
    integer timeout_counter;
    
    // Execution Control Flags
    reg tx_done; 

    // Instantiate the Decompressor DUT
    axi_wrapper dut (
        .aclk(aclk),
        .aresetn(aresetn),
        .s_axis_tdata(s_axis_tdata),
        .s_axis_tvalid(s_axis_tvalid),
        .s_axis_tready(s_axis_tready),
        .s_axis_tlast(s_axis_tlast),
        .m_axis_tdata(m_axis_tdata),
        .m_axis_tvalid(m_axis_tvalid),
        .m_axis_tready(m_axis_tready),
        .m_axis_tlast(m_axis_tlast)
    );

    // Clock Generation
    initial begin
        aclk = 0;
        forever #(CLK_PERIOD/2) aclk = ~aclk;
    end

    // Block 1: Read compressed data from file and transmit to Decompressor
    initial begin
        // Initialize inputs
        aresetn       = 0;
        s_axis_tdata  = 16'h0000;
        s_axis_tvalid = 0;
        s_axis_tlast  = 0;
        tx_done       = 0;

        // Open the file generated by your compressor
        file_in = $fopen("C:/Users/nisha/Downloads/compressorop.txt", "r");
        if (file_in == 0) begin
            $display("======================================================================");
            $display("CRITICAL ERROR: Could not open C:/Users/nisha/Downloads/compressorop.txt");
            $display("======================================================================");
            $finish;
        end

        // Reset Sequence
        #(CLK_PERIOD * 4);
        aresetn = 1;
        
        // Let pipeline settle post-reset
        #(CLK_PERIOD * 2);

        // Read file sequentially and stream via AXI protocol
        status = $fscanf(file_in, "%h\n", temp_val);
        while (status == 1) begin
            
            // Step 1: Wait for a clean clock edge, then apply data (exactly like send_packet)
            @(posedge aclk);
            #1; // Minor delta delay matching your original task logic
            s_axis_tdata  = temp_val;
            s_axis_tvalid = 1;
            
            if ($feof(file_in)) begin
                s_axis_tlast = 1;
            end else begin
                s_axis_tlast = 0;
            end

            // Step 2: HOLD the data steady as long as tready is low.
            // Do NOT read a new line from the file until the handshake is complete.
            while (!s_axis_tready) begin
                @(posedge aclk);
                #1;
            end
            
            // Step 3: Handshake achieved! Clear valid for a clean cycle transition
            @(posedge aclk);
            #1;
            s_axis_tvalid = 0;
            s_axis_tlast  = 0;
            
            // Add a small inter-packet delay if your original hardcoded flow had them (#40)
            // If your core supports back-to-back streaming, you can comment this next line out.
            #(CLK_PERIOD * 4); 

            // Step 4: Now it is safe to fetch the next record from the text file
            if (!s_axis_tlast) begin
                status = $fscanf(file_in, "%h\n", temp_val);
            end else begin
                status = 0; // End loop safely
            end
        end

        s_axis_tvalid = 0;
        s_axis_tlast  = 0;
        $fclose(file_in);
        $display("Finished transmitting all compressed data to Decompressor.");
        
        tx_done = 1;
    end

    // Block 2: Capture decompressed master outputs and log them directly to file
    initial begin
        m_axis_tready   = 1; // Decompressor sink is always ready
        timeout_counter = 0;

        file_out = $fopen("C:/Users/nisha/Downloads/decompressorop.txt", "w");
        if (file_out == 0) begin
            $display("ERROR: Could not create output file decompressorop.txt");
            $finish;
        end

        wait(aresetn == 1);

        forever begin
            @(posedge aclk);
            
            if (m_axis_tvalid && m_axis_tready) begin
                timeout_counter <= 0; // Reset idle timer
                
                $display("Time=%0t ps: Out Data Collected = %h, m_axis_tlast = %b", 
                         $time, m_axis_tdata, m_axis_tlast);
                
                if (^m_axis_tdata !== 1'bx) begin
                    $fwrite(file_out, "%h\n", m_axis_tdata);
                end
                
                if (m_axis_tlast) begin
                    $display("Decompressed stream completed successfully via Master TLAST.");
                    #100;
                    $fclose(file_out);
                    $finish;
                end
                
            end else begin
                if (tx_done) begin
                    timeout_counter <= timeout_counter + 1;
                end
            end

            // Timeout exit fallback loop
            if (timeout_counter > 500) begin
                $display("Simulation timed out safely after decompressor flushed clean.");
                #100;
                $fclose(file_out);
                $finish;
            end
        end
    end

endmodule